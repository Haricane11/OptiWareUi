def seed():
    conn = get_conn()
    cur = conn.cursor()
    
    for table, rows in DATA.items():
        if not rows:
            continue
            
        print(f"Seeding {table}...")
        columns = list(rows[0].keys())
        
        # Build the INSERT statement
        col_names = ", ".join(columns)
        placeholders = ", ".join(["%s"] * len(columns))
        insert_query = f"INSERT INTO {table} ({col_names}) VALUES ({placeholders}) ON CONFLICT DO NOTHING"
        label_map = {
            'EXPIRY': 'EXPIRY_RISK',
            'DEAD': 'DEAD_STOCK',
            'SLOW': 'SLOW_MOVING',
            # Add any others here if they pop up
        }
        for row in rows:
            values = []
            for col in columns:
                val = row[col]
                
                # FIX: Handle dictionaries for JSONB columns
                if isinstance(val, dict):
                    val = Json(val)
                
                # Handle dates (ISO strings to datetime objects)
                elif isinstance(val, str) and len(val) >= 10:
                    try:
                        if len(val) == 10:
                            val = datetime.datetime.strptime(val, '%Y-%m-%d').date()
                        else:
                            # Replace Z with UTC offset for ISO format compatibility
                            val = datetime.datetime.fromisoformat(val.replace('Z', '+00:00'))
                    except Exception:
                        pass
                
                values.append(val)
            
            try:
                cur.execute(insert_query, tuple(values))
            except Exception as e:
                # Rollback the specific failed row so the loop can continue
                conn.rollback()
                print(f"Error seeding {table}: {e}")
                
    conn.commit()
    cur.close()
    conn.close()
    print("Seeding complete!")

if __name__ == '__main__':
    seed()
